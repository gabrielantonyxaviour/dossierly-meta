"""Regenerates src/messages/index.ts from the JSON files under src/messages/en. Run: python3 scripts/gen-messages-index.py"""
import os
base = os.path.join(os.path.dirname(__file__), "..", "src", "messages")
ns = sorted(f[:-5] for f in os.listdir(os.path.join(base, "en")) if f.endswith(".json"))
ident = lambda loc, n: loc + "".join(p[:1].upper() + p[1:] for p in n.replace("-", "_").split("_"))
L = ["/* GENERATED by scripts/gen-messages-index.py from src/messages/en/*.json. Do not edit by hand.",
     "   Interface strings per locale and namespace. English is the source; a missing key falls back to it.",
     "   Add a namespace: create src/messages/<locale>/<ns>.json for all four locales, then rerun the script. */",
     'import type { Locale } from "@/lib/i18n/locales";']
for loc in ["en", "hi", "uk", "ta"]:
    for n in ns:
        L.append(f'import {ident(loc, n)} from "./{loc}/{n}.json";')
L.append("")
def obj(loc): return "{ " + ", ".join(f'"{n}": {ident(loc, n)}' for n in ns) + " }"
L.append(f"const en = {obj('en')} as const;")
L.append("export type Namespace = keyof typeof en;")
L.append("type Dict = { [N in Namespace]?: Record<string, string> };")
L.append("")
L.append("export const MESSAGES: Record<Locale, Dict> & { en: typeof en } = {")
L.append("  en,")
for loc in ["hi", "uk", "ta"]:
    L.append(f"  {loc}: {obj(loc)},")
L.append("};")
open(os.path.join(base, "index.ts"), "w").write("\n".join(L) + "\n")
